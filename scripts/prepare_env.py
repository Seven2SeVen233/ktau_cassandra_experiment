"""Sync the docker section of config.yaml into the .env file used for docker
compose interpolation.

docker compose automatically reads the .env file at the project root on startup.
config.yaml is the single source of truth: after editing its docker section,
re-run this script; no need to maintain two configs by hand.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common

# config.yaml docker-section keys -> compose environment variable names
# Note: the network is declared statically in docker-compose.yml and does not
# support interpolation, so it is not exported.
MAP = {
    "image": "CASSANDRA_IMAGE",
    "cluster_name": "CASSANDRA_CLUSTER_NAME",
    "dc": "CASSANDRA_DC",
    "rack": "CASSANDRA_RACK",
    "container_prefix": "CASSANDRA_CONTAINER_PREFIX",
    "client_port": "CASSANDRA_CLIENT_PORT",
    "heap_size": "CASSANDRA_MAX_HEAP",
    "heap_newsize": "CASSANDRA_HEAP_NEWSIZE",
    "cpu_limit": "CASSANDRA_CPU_LIMIT",
    "mem_limit": "CASSANDRA_MEM_LIMIT",
}


def main():
    cfg = common.load_config()
    docker_cfg = cfg["docker"]
    lines = ["# Auto-generated by scripts/prepare_env.py; edit config.yaml and re-run."]
    for key, env in MAP.items():
        lines.append(f"{env}={docker_cfg[key]}")
    out = os.path.join(common.BASE, ".env")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")
    for l in lines:
        print("  " + l)


if __name__ == "__main__":
    main()
