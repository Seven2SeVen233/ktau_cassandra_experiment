"""Phase 5: result summarization → results/experiment_report.md + console summary.

Reads E1–E6a and perf_*.csv, produces quantitative tables and key conclusions.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import pandas as pd

import common
from common import log


def _load(name):
    path = os.path.join(common.RESULTS, name)
    if not os.path.exists(path):
        log.warning("missing result file: %s", name)
        return None
    return pd.read_csv(path)


def fmt(x, nd=4):
    try:
        return f"{x:.{nd}f}"
    except Exception:
        return str(x)


def main():
    common.ensure_results()
    lines = ["# Kendall τ / Ranked Pairs experiment report\n"]
    lines.append("> Auto-generated by analyze_results.py. Data sources: results/*.csv.\n")

    # ---- E1 causal decomposition ----
    df = _load("e1_causal_decomp.csv")
    if df is not None:
        lines.append("## E1 τ-distance causal decomposition (means)\n")
        lines.append("| conflict | strategy | τ_causal | τ_contested | τ̂ | info_retention |")
        lines.append("|---|---|---|---|---|---|")
        g = df.groupby(["conflict", "strategy"])[
            ["tau_causal", "tau_contested", "tauhat", "info_retention"]].mean()
        for (conf, strat), r in g.iterrows():
            lines.append(f"| {conf} | {strat} | {r['tau_causal']:.4f} | "
                         f"{r['tau_contested']:.4f} | {r['tauhat']:.4f} | {r['info_retention']:.4f} |")
        lines.append("")

    # ---- E1b counterexample ----
    df = _load("e1b_counterexample.csv")
    if df is not None:
        r = df.iloc[0]
        lines.append("## E1b paper counterexample reproduction\n")
        lines.append(f"- When the consistent constraint is violated, τ_causal = {r['tau_causal']:.0f} "
                     f"(= n_ab), τ_total = {r['tau_total']:.0f}, τ̂ = {r['tauhat']:.4f}. "
                     "τ counts violated causal constraints exactly, deterministically.\n")

    # ---- E2 end-to-end ----
    df = _load("e2_end2end.csv")
    if df is not None:
        lines.append("## E2 end-to-end comparison (high conflict)\n")
        lines.append("| strategy | ops_retained | auto_coverage | info_retention | τ_causal | "
                     "semantic_validity | Gini | time_ms |")
        lines.append("|---|---|---|---|---|---|---|---|")
        g = df.groupby("strategy")[
            ["ops_retained", "auto_coverage", "info_retention", "tau_causal",
             "semantic_validity", "gini", "time_ms"]].mean()
        for strat, r in g.iterrows():
            lines.append(f"| {strat} | {r['ops_retained']:.4f} | {r['auto_coverage']:.4f} | "
                         f"{r['info_retention']:.4f} | {r['tau_causal']:.4f} | "
                         f"{r['semantic_validity']:.4f} | {r['gini']:.4f} | {r['time_ms']:.4f} |")
        lines.append("")

    # ---- E3 RP vs Kemeny ----
    df = _load("e3_rp_vs_kemeny.csv")
    if df is not None:
        lines.append("## E3 Ranked Pairs vs exact Kemeny\n")
        lines.append("| M | RP=exact Kemeny rate | avg excess % | max excess % | Kemeny time(ms) |")
        lines.append("|---|---|---|---|---|")
        g = df.groupby("M").agg(
            rp_exact_rate=("rp_exact", "mean"),
            avg_excess_pct=("excess_pct", "mean"),
            max_excess_pct=("excess_pct", "max"),
            kemeny_ms=("kemeny_ms", "mean"))
        for M, r in g.iterrows():
            lines.append(f"| {M} | {r['rp_exact_rate']:.3f} | {r['avg_excess_pct']:.4f} | "
                         f"{r['max_excess_pct']:.4f} | {r['kemeny_ms']:.4f} |")
        lines.append("")

    # ---- E4 monitoring ----
    df = _load("e4_monitor.csv")
    if df is not None:
        lines.append("## E4 real-time τ monitoring\n")
        lines.append("| drift_max | detect delay(s) | maxlag@detect | steady false alarms | peak τ̂ | "
                     "partition peak τ̂ | jac partition min | jac heal max |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for _, r in df.iterrows():
            det = fmt(r["detect_delay_s"]) if pd.notna(r["detect_delay_s"]) else "N/A"
            ml = int(r["maxlag_at_detect"]) if pd.notna(r["maxlag_at_detect"]) else "N/A"
            jpm = fmt(r["jac_partition_min"]) if pd.notna(r["jac_partition_min"]) else "N/A"
            jhm = fmt(r["jac_heal_max"]) if pd.notna(r["jac_heal_max"]) else "N/A"
            lines.append(f"| {r['drift_max']:.2f} | {det} | {ml} | "
                         f"{int(r['false_alarms_steady'])} | {r['peak_tauhat']:.4f} | "
                         f"{r['peak_partition_tauhat']:.4f} | {jpm} | {jhm} |")
        lines.append("")
        lines.append("> Trajectory data: `results/e4_monitor_series.csv` (trial, phase, τ̂, maxlag, "
                     "jaccard). During drift, maxlag≡0 while τ̂ rises, showing that τ detects "
                     "ordering divergence invisible to binary lag; during partition, τ̂≈0 while "
                     "Jaccard drops, showing the two are complementary.\n")

    # ---- E5 performance ----
    df = _load("e5_perf.csv")
    if df is not None:
        lines.append("## E5 performance and scalability (p50)\n")
        lines.append("| M | τ_total(ms) | RP(ms) | LWW(ms) | VC(ms) | merge throughput(ops/s) |")
        lines.append("|---|---|---|---|---|---|")
        g = df.groupby("M")[
            ["tau_total_ms", "rp_ms", "lww_ms", "vc_ms", "merge_thr_ops_s"]].quantile(0.5)
        for M, r in g.iterrows():
            lines.append(f"| {M} | {r['tau_total_ms']:.3f} | {r['rp_ms']:.3f} | "
                         f"{r['lww_ms']:.3f} | {r['vc_ms']:.3f} | {r['merge_thr_ops_s']:.1f} |")
        lines.append("")

    # ---- E6a partition asymmetry ----
    df = _load("e6a_asymmetry.csv")
    if df is not None:
        lines.append("## E6a partition asymmetry (minority-fraction sweep)\n")
        lines.append("| minority_frac | strategy | ops_retained | info_retention | τ̂ |")
        lines.append("|---|---|---|---|---|")
        g = df.groupby(["minority_frac", "strategy"])[
            ["ops_retained", "info_retention", "tauhat"]].mean()
        for (fr, strat), r in g.iterrows():
            lines.append(f"| {fr:.2f} | {strat} | {r['ops_retained']:.4f} | "
                         f"{r['info_retention']:.4f} | {r['tauhat']:.4f} |")
        lines.append("")

    # ---- perf ----
    df = _load("perf_host.csv")
    if df is not None:
        lines.append("## Cluster resource utilization (docker stats sample means)\n")
        lines.append("| node | CPU% | mem(MB) | net rx(MB) | net tx(MB) |")
        lines.append("|---|---|---|---|---|")
        g = df.groupby("node")[["cpu_pct", "mem_mb", "net_rx", "net_tx"]].mean()
        for node, r in g.iterrows():
            lines.append(f"| {node} | {r['cpu_pct']:.1f} | {r['mem_mb']:.0f} | "
                         f"{r['net_rx']:.1f} | {r['net_tx']:.1f} |")
        lines.append("")

    df = _load("perf_cql_latency.csv")
    if df is not None:
        p = dict(zip(df["metric"], df["ms"]))
        lines.append("## CQL round-trip latency (ms)\n")
        lines.append(f"- p50 = {p.get('p50', 'N/A')}, p95 = {p.get('p95', 'N/A')}, "
                     f"p99 = {p.get('p99', 'N/A')}\n")

    # ---- statistical tests (stats.py products, if present) ----
    for tag, sub in (("synthetic", "synthetic"), ("trace", "")):
        base = os.path.join(common.RESULTS, sub, f"statistics_{tag}_summary.csv") if sub \
            else os.path.join(common.RESULTS, f"statistics_{tag}_summary.csv")
        wil_path = os.path.join(common.RESULTS, sub, f"statistics_{tag}_wilcoxon.csv") if sub \
            else os.path.join(common.RESULTS, f"statistics_{tag}_wilcoxon.csv")
        if not os.path.exists(base):
            continue
        lines.append(f"## Statistical tests ({tag}) — mean±std (95%CI)\n")
        sdf = pd.read_csv(base)
        wdf = pd.read_csv(wil_path)
        for (gname,), g in sdf.groupby("metric"):
            lines.append(f"### {gname}\n")
            cols = [c for c in ["conflict", "minority_frac", "strategy"] if c in g.columns]
            if not cols:
                cols = ["strategy"]
            lines.append("| " + " | ".join(cols) + " | mean±std | 95% CI | n |")
            lines.append("|---|---|---|---|---|")
            for _, r in g.sort_values(cols).iterrows():
                cell = " | ".join(str(r[c]) for c in cols)
                if pd.isna(r["ci95_low"]) or pd.isna(r["ci95_high"]):
                    ci = "N/A"
                else:
                    ci = f"[{r['ci95_low']:.4f}, {r['ci95_high']:.4f}]"
                lines.append(f"| {cell} | {r['mean']:.4f}±{r['std']:.4f} | {ci} | {int(r['n'])} |")
            lines.append("")
        sig = wdf[(wdf["significant"]) & (wdf["note"] == "")]
        if len(sig):
            lines.append(f"**Significant differences (paired Wilcoxon, α=0.05, info_retention):** "
                         + "; ".join(f"{r['strategy_a']} vs {r['strategy_b']}"
                                     f" (p={r['p']:.4f}, n={int(r['n'])})"
                                     for _, r in sig.iterrows()) + "\n")
        tie = wdf[wdf["note"] == "tied"]
        if len(tie):
            lines.append(f"**Isomorphic (indistinguishable, all-zero differences):** "
                         + "; ".join(f"{r['strategy_a']} ≡ {r['strategy_b']}"
                                     for _, r in tie.iterrows()) + "\n")

    out = os.path.join(common.RESULTS, "experiment_report.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    log.info("report generated: %s", out)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
